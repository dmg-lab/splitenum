#!/usr/bin/env python3
"""Emit a LaTeX longtable of the per-scheme node counts of a finished run.

Usage: scheme_tables.py RUNDIR --label LABEL --caption TEXT [--pairs K]
                        [--size \\footnotesize] > FILE.tex

RUNDIR holds types.csv and run.json of a finished run.  Rows of types.csv
are summed per `viro`, the sum over all schemes must equal `total_nodes`
of run.json, and the schemes are listed by count, descending, filled
column-major into K scheme/count pairs per row.  Scheme macros follow
the abstract's `\\scheme{...}` convention; counts are set in math mode
with `{,}` separators in a left-aligned column, shares with four decimals at or above 0.001 %
and in scientific notation below.
"""

import argparse
import csv
import json
import math
import sys


def viro_to_tex(viro):
    out = []
    for ch in viro:
        if ch == "<":
            out.append("\\scheme{")
        elif ch == ">":
            out.append("}")
        elif ch == "v":
            out.append("\\sqcup ")
        else:
            out.append(ch)
    return "".join(out)


def group_digits(n):
    return "{,}".join(reversed([str(n)[::-1][i:i + 3][::-1]
                                for i in range(0, len(str(n)), 3)]))


def share_tex(count, total):
    pct = 100 * count / total
    if pct >= 1e-3:
        return f"{pct:.4f}\\%"
    exp = math.floor(math.log10(pct))
    mant = pct / 10 ** exp
    if round(mant, 1) >= 10:
        mant /= 10
        exp += 1
    return f"{mant:.1f}\\cdot 10^{{{exp}}}\\%"


def cell(viro, count, total):
    return (f"${viro_to_tex(viro)}$ & ${group_digits(count)}$ & "
            f"(${share_tex(count, total)}$)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("rundir")
    ap.add_argument("--label", required=True)
    ap.add_argument("--caption", required=True)
    ap.add_argument("--pairs", type=int, default=2)
    ap.add_argument("--size", default="\\footnotesize")
    ap.add_argument("--colsep", default="3pt")
    args = ap.parse_args()

    totals = {}
    with open(f"{args.rundir}/types.csv", newline="") as f:
        for row in csv.DictReader(f):
            totals[row["viro"]] = totals.get(row["viro"], 0) + int(row["count"])
    with open(f"{args.rundir}/run.json") as f:
        run = json.load(f)
    total = run["total_nodes"]
    if sum(totals.values()) != total:
        sys.exit(f"sum of counts {sum(totals.values())} != total_nodes {total}")
    print(f"{len(totals)} schemes, {total} nodes, delta {run['delta']}",
          file=sys.stderr)

    entries = sorted(totals.items(), key=lambda kv: (-kv[1], kv[0]))
    k = args.pairs
    r = math.ceil(len(entries) / k)
    head = " & ".join(["scheme & collections & share"] * k) + " \\\\"
    spec = "@{}" + "@{\\hspace{2em}}".join(["llr"] * k) + "@{}"

    lines = [
        f"% Generated by tools/scheme_tables.py of splitenum from {args.rundir},",
        f"% degree {run['delta']} with {run['nsplits']} splits, "
        f"{total} compatible collections, {len(totals)} schemes.",
        "{" + args.size,
        f"\\setlength{{\\tabcolsep}}{{{args.colsep}}}",
        f"\\begin{{longtable}}{{{spec}}}",
        f"\\caption{{{args.caption}}}\\label{{{args.label}}}\\\\",
        "\\toprule",
        head,
        "\\midrule",
        "\\endfirsthead",
        "\\caption[]{Continued.}\\\\",
        "\\toprule",
        head,
        "\\midrule",
        "\\endhead",
        "\\bottomrule",
        "\\endfoot",
    ]
    for i in range(r):
        cells = []
        for j in range(k):
            idx = j * r + i
            if idx < len(entries):
                cells.append(cell(entries[idx][0], entries[idx][1], total))
            else:
                cells.append(" & & ")
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\end{longtable}", "}"]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
